//! The task repository port and its supporting query types.

use async_trait::async_trait;

use crate::application::AppError;
use crate::domain::task::{
    DueDate, NewTask, Task, TaskDescription, TaskId, TaskPriority, TaskStatus, TaskTitle,
};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SortField {
    CreatedAt,
    UpdatedAt,
    DueDate,
    Priority,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SortOrder {
    Asc,
    Desc,
}

/// Filters combine with AND across fields and OR within one field. An empty
/// list means "no filter on that field".
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct TaskFilters {
    pub statuses: Vec<TaskStatus>,
    pub priorities: Vec<TaskPriority>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TaskQuery {
    pub filters: TaskFilters,
    pub sort: SortField,
    pub order: SortOrder,
    pub limit: i64,
    pub offset: i64,
}

impl Default for TaskQuery {
    fn default() -> Self {
        Self {
            filters: TaskFilters::default(),
            sort: SortField::CreatedAt,
            order: SortOrder::Desc,
            limit: 20,
            offset: 0,
        }
    }
}

/// One page of tasks; `total` counts every row matching the filters.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TaskPage {
    pub items: Vec<Task>,
    pub total: i64,
}

/// A change to a field: leave it, set it, or (nullable fields) clear it.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub enum FieldPatch<T> {
    #[default]
    Keep,
    Set(T),
    Clear,
}

/// A partial update. Callers ensure at least one field changes.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct TaskPatch {
    pub title: Option<TaskTitle>,
    pub description: FieldPatch<TaskDescription>,
    pub status: Option<TaskStatus>,
    pub priority: Option<TaskPriority>,
    pub due_date: FieldPatch<DueDate>,
}

#[async_trait]
pub trait TaskRepository: Send + Sync {
    /// Persists a validated task; id and timestamps are generated by the
    /// store.
    async fn create(&self, task: &NewTask) -> Result<Task, AppError>;
    async fn find_by_id(&self, id: TaskId) -> Result<Option<Task>, AppError>;
    async fn list(&self, query: &TaskQuery) -> Result<TaskPage, AppError>;
    /// Applies the patch and refreshes `updated_at`; `None` when unknown.
    async fn update(&self, id: TaskId, patch: &TaskPatch) -> Result<Option<Task>, AppError>;
    /// `true` when a row was removed.
    async fn delete(&self, id: TaskId) -> Result<bool, AppError>;
}
