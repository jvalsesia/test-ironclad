//! Request and response bodies for the task endpoints.

use std::fmt;

use chrono::{DateTime, SecondsFormat, Utc};
use serde::de::value::MapAccessDeserializer;
use serde::de::{MapAccess, Visitor};
use serde::{Deserialize, Deserializer, Serialize};
use utoipa::ToSchema;

use crate::domain::task::{RawField, RawNewTask, RawTaskChanges, Task};
use crate::http::openapi::schemas::{TaskPrioritySchema, TaskStatusSchema};

/// `POST /tasks` body. Every field is optional text so a missing or `null`
/// title is a domain validation error (422) while a wrongly typed value is
/// the extractor's 400. Unknown fields are ignored.
///
/// The OpenAPI schema advertises the accepted shape: `title` required and
/// non-null, `status`/`priority` non-null with their defaults (the server's
/// tolerance of `null` there is not advertised).
#[derive(Debug, Deserialize, ToSchema)]
#[schema(
    description = "Body of POST /tasks. Unknown fields are ignored; id and timestamps are generated by the server."
)]
pub struct CreateTaskRequest {
    /// 1-200 characters after trimming leading and trailing whitespace
    #[schema(value_type = String, required = true, min_length = 1, max_length = 200)]
    pub title: Option<String>,
    /// Up to 5000 characters
    #[schema(max_length = 5000)]
    pub description: Option<String>,
    #[schema(value_type = TaskStatusSchema, required = false, default = "todo")]
    pub status: Option<String>,
    #[schema(value_type = TaskPrioritySchema, required = false, default = "medium")]
    pub priority: Option<String>,
    /// Calendar date, YYYY-MM-DD
    #[schema(format = Date)]
    pub due_date: Option<String>,
}

impl From<CreateTaskRequest> for RawNewTask {
    fn from(request: CreateTaskRequest) -> Self {
        Self {
            title: request.title,
            description: request.description,
            status: request.status,
            priority: request.priority,
            due_date: request.due_date,
        }
    }
}

/// `PATCH /tasks/{id}` body. Each field is three-state: absent (left
/// unchanged), `null`, or a string. A wrongly typed value is the
/// extractor's 400 naming the field. Unknown fields are ignored. Only a JSON
/// object is accepted (serde would otherwise take `[]` as an empty struct).
#[derive(Debug, Default, ToSchema)]
#[schema(
    description = "Body of PATCH /tasks/{id}. Every field is optional, but at least one updatable field must be provided. `null` clears `description` or `due_date`; `title`, `status` and `priority` cannot be null. Unknown fields are ignored and do not count."
)]
pub struct UpdateTaskRequest {
    /// 1-200 characters after trimming leading and trailing whitespace
    #[schema(value_type = String, required = false, min_length = 1, max_length = 200)]
    pub title: RawField,
    /// Up to 5000 characters; null clears it
    #[schema(value_type = Option<String>, required = false, max_length = 5000)]
    pub description: RawField,
    #[schema(value_type = TaskStatusSchema, required = false)]
    pub status: RawField,
    #[schema(value_type = TaskPrioritySchema, required = false)]
    pub priority: RawField,
    /// Calendar date, YYYY-MM-DD; null clears it
    #[schema(value_type = Option<String>, required = false, format = Date)]
    pub due_date: RawField,
}

impl<'de> Deserialize<'de> for UpdateTaskRequest {
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: Deserializer<'de>,
    {
        deserializer.deserialize_map(ObjectOnly)
    }
}

/// Accepts only a map, then hands it to the derived field deserializer so
/// field paths are still reported for wrongly typed values.
struct ObjectOnly;

impl<'de> Visitor<'de> for ObjectOnly {
    type Value = UpdateTaskRequest;

    fn expecting(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str("a JSON object")
    }

    fn visit_map<A>(self, map: A) -> Result<Self::Value, A::Error>
    where
        A: MapAccess<'de>,
    {
        UpdateTaskFields::deserialize(MapAccessDeserializer::new(map)).map(|fields| {
            UpdateTaskRequest {
                title: fields.title,
                description: fields.description,
                status: fields.status,
                priority: fields.priority,
                due_date: fields.due_date,
            }
        })
    }
}

#[derive(Deserialize)]
struct UpdateTaskFields {
    #[serde(default, deserialize_with = "three_state")]
    pub title: RawField,
    #[serde(default, deserialize_with = "three_state")]
    pub description: RawField,
    #[serde(default, deserialize_with = "three_state")]
    pub status: RawField,
    #[serde(default, deserialize_with = "three_state")]
    pub priority: RawField,
    #[serde(default, deserialize_with = "three_state")]
    pub due_date: RawField,
}

/// Runs only for a present key (absent keys take the `Absent` default), so
/// `null` and a string value are the two remaining states.
fn three_state<'de, D>(deserializer: D) -> Result<RawField, D::Error>
where
    D: Deserializer<'de>,
{
    Ok(match Option::<String>::deserialize(deserializer)? {
        Some(text) => RawField::Value(text),
        None => RawField::Null,
    })
}

impl From<UpdateTaskRequest> for RawTaskChanges {
    fn from(request: UpdateTaskRequest) -> Self {
        Self {
            title: request.title,
            description: request.description,
            status: request.status,
            priority: request.priority,
            due_date: request.due_date,
        }
    }
}

/// The task representation shared by every task endpoint, published in the
/// OpenAPI document as `Task`.
#[derive(Debug, Serialize, ToSchema)]
#[schema(as = Task, description = "A task")]
pub struct TaskResponse {
    /// Server-generated id
    #[schema(format = Uuid)]
    pub id: String,
    /// 1-200 characters after trimming leading and trailing whitespace
    #[schema(min_length = 1, max_length = 200)]
    pub title: String,
    /// Up to 5000 characters
    #[schema(required = true, max_length = 5000)]
    pub description: Option<String>,
    #[schema(value_type = TaskStatusSchema)]
    pub status: String,
    #[schema(value_type = TaskPrioritySchema)]
    pub priority: String,
    /// Calendar date, YYYY-MM-DD
    #[schema(required = true, format = Date)]
    pub due_date: Option<String>,
    /// RFC 3339 UTC, millisecond precision
    #[schema(format = DateTime)]
    pub created_at: String,
    /// RFC 3339 UTC, millisecond precision
    #[schema(format = DateTime)]
    pub updated_at: String,
}

/// RFC 3339 UTC with exactly three fractional digits; microseconds are
/// truncated, not rounded.
fn format_timestamp(value: DateTime<Utc>) -> String {
    value.to_rfc3339_opts(SecondsFormat::Millis, true)
}

impl From<&Task> for TaskResponse {
    fn from(task: &Task) -> Self {
        Self {
            id: task.id().value().to_string(),
            title: task.title().as_str().to_owned(),
            description: task.description().map(|d| d.as_str().to_owned()),
            status: task.status().as_str().to_owned(),
            priority: task.priority().as_str().to_owned(),
            due_date: task
                .due_date()
                .map(|d| d.value().format("%Y-%m-%d").to_string()),
            created_at: format_timestamp(task.created_at()),
            updated_at: format_timestamp(task.updated_at()),
        }
    }
}

#[cfg(test)]
mod tests {
    use chrono::TimeZone;
    use uuid::Uuid;

    use crate::domain::task::{TaskId, TaskParts, TaskPriority, TaskStatus, TaskTitle};
    use crate::http::error::{ApiError, ErrorCode};
    use crate::http::extract::parse_json;

    use super::*;

    fn task_at(created: DateTime<Utc>) -> Task {
        Task::restore(TaskParts {
            id: TaskId::new(Uuid::nil()),
            title: TaskTitle::restore("Write PRD".into()),
            description: None,
            status: TaskStatus::Todo,
            priority: TaskPriority::High,
            due_date: None,
            created_at: created,
            updated_at: created,
        })
    }

    #[test]
    fn response_field_order_and_nulls() {
        let created = Utc.with_ymd_and_hms(2026, 11, 21, 18, 11, 0).unwrap();
        let json = serde_json::to_string(&TaskResponse::from(&task_at(created))).unwrap();
        assert_eq!(
            json,
            r#"{"id":"00000000-0000-0000-0000-000000000000","title":"Write PRD","description":null,"status":"todo","priority":"high","due_date":null,"created_at":"2026-11-21T18:11:00.000Z","updated_at":"2026-11-21T18:11:00.000Z"}"#
        );
    }

    #[test]
    fn missing_null_and_value_are_distinct() {
        let empty: UpdateTaskRequest = serde_json::from_str("{}").unwrap();
        assert_eq!(empty.due_date, RawField::Absent);
        assert_eq!(empty.title, RawField::Absent);

        let null: UpdateTaskRequest = serde_json::from_str(r#"{"due_date":null}"#).unwrap();
        assert_eq!(null.due_date, RawField::Null);
        assert_eq!(null.description, RawField::Absent);

        let value: UpdateTaskRequest =
            serde_json::from_str(r#"{"due_date":"2026-12-01","color":"red"}"#).unwrap();
        assert_eq!(value.due_date, RawField::Value("2026-12-01".into()));

        let raw = RawTaskChanges::from(value);
        assert_eq!(raw.due_date, RawField::Value("2026-12-01".into()));
        assert_eq!(raw.status, RawField::Absent);
    }

    #[test]
    fn wrong_type_names_the_field() {
        let err = parse_json::<UpdateTaskRequest>(br#"{"status":"done","title":5}"#).unwrap_err();
        assert_eq!(err.code, ErrorCode::InvalidJson);
        assert_eq!(err.details.len(), 1);
        assert_eq!(err.details[0].field, "title");
    }

    #[test]
    fn non_object_body_is_invalid_json_without_details() {
        for body in ["null", "[]", r#""done""#, "5"] {
            let err = parse_json::<UpdateTaskRequest>(body.as_bytes()).unwrap_err();
            assert_eq!(err, ApiError::invalid_json(Vec::new()), "{body}");
        }
    }

    #[test]
    fn timestamps_use_millisecond_utc_format() {
        let created = Utc
            .with_ymd_and_hms(2026, 11, 21, 18, 11, 0)
            .unwrap()
            .checked_add_signed(chrono::Duration::microseconds(123_999))
            .unwrap();
        let response = TaskResponse::from(&task_at(created));
        assert_eq!(response.created_at, "2026-11-21T18:11:00.123Z");
    }
}
